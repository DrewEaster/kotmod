package io.querty.codegen

import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import kotlin.io.path.ExperimentalPathApi
import kotlin.io.path.createDirectories
import kotlin.io.path.deleteIfExists
import kotlin.io.path.deleteRecursively
import kotlin.io.path.exists
import kotlin.io.path.extension
import kotlin.io.path.invariantSeparatorsPathString
import kotlin.io.path.isDirectory
import kotlin.io.path.isRegularFile
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.readBytes
import kotlin.io.path.readText
import kotlin.io.path.relativeTo
import kotlin.io.path.walk
import kotlin.io.path.writeText

/** [schema] is a list of scripts and directories of scripts, ordered by [SchemaScripts]. */
data class GeneratorConfig(val sqlDir: Path, val schema: List<Path>, val outDir: Path, val image: String = "postgres:17")

/** Runs the whole pipeline: parse, rewrite, describe against the schema, build models, emit and write. */
@OptIn(ExperimentalPathApi::class)
object Generator {
    private const val HEADER = "// Generated by Querty"

    /** Writes the generated files into [GeneratorConfig.outDir], or writes nothing and throws with every error. */
    fun generate(config: GeneratorConfig) {
        write(render(config), config.outDir)
    }

    /** The differences between what would be generated and [GeneratorConfig.outDir]; empty when up to date. */
    fun check(config: GeneratorConfig): List<String> {
        val expected = render(config)
        val actual = generatedFiles(config.outDir)
        return (expected.keys + actual.keys).sorted().mapNotNull { path ->
            val file = actual[path]
            when {
                file == null -> "missing: $path"
                path !in expected -> "extra: $path"
                !file.readBytes().contentEquals(expected.getValue(path).toByteArray()) -> "stale: $path"
                else -> null
            }
        }
    }

    /** The generated sources, keyed by their path under the output directory with `/` separators. */
    private fun render(config: GeneratorConfig): Map<String, String> {
        val parsed = parse(config.sqlDir)
        val snippets = snippets(parsed)

        val errors = mutableListOf<QuertyError>()
        val rewritten = parsed.associateWith { file ->
            file.queries.mapNotNull { query -> collect(errors) { query to SqlRewriter.rewrite(query, snippets) } }
        }

        val models = mutableMapOf<ParsedFile, List<QueryModel>>()
        if (rewritten.values.any { it.isNotEmpty() }) {
            collect(errors) {
                SchemaDatabase(config.image, SchemaScripts.ordered(config.schema)).use { db ->
                    val describer = QueryDescriber(db.connection)
                    rewritten.forEach { (file, queries) ->
                        models[file] = queries.mapNotNull { (query, sql) -> collect(errors) { model(file, query, sql, describer) } }
                    }
                }
            }
        }
        if (errors.isNotEmpty()) throw QuertyException(errors.sortedWith(compareBy({ it.file }, { it.line })))

        val outputs = linkedMapOf<String, String>()
        for (file in parsed) {
            val fileModels = models[file].orEmpty().takeIf { it.isNotEmpty() } ?: continue
            outputs[outputPath(file.path)] = KotlinEmitter.emit(file.path.substringBeforeLast('/').replace('/', '.'), fileModels)
        }
        return outputs
    }

    /** Every `.sql` file under [sqlDir], in path order, named by its path relative to [sqlDir]. */
    private fun parse(sqlDir: Path): List<ParsedFile> {
        val errors = mutableListOf<QuertyError>()
        val files = sqlDir.walk().filter { it.isRegularFile() && it.extension == "sql" }
            .map { it.relativeTo(sqlDir).invariantSeparatorsPathString to it }
            .sortedBy { it.first }
            .toList()
        val parsed = files.mapNotNull { (path, file) -> collect(errors) { SqlFileParser.parse(path, file.readText()) } }
        parsed.filter { '/' !in it.path && it.queries.isNotEmpty() }.forEach {
            errors += QuertyError(it.path, it.queries.first().line, "Queries must be in a directory under the sql dir; the directory gives their package")
        }
        parsed.filter { it.queries.isNotEmpty() }.groupBy { outputPath(it.path) }.values.filter { it.size > 1 }.forEach { clash ->
            clash.drop(1).forEach { errors += QuertyError(it.path, 1, "Generates the same file as ${clash.first().path}; rename one of them") }
        }
        if (errors.isNotEmpty()) throw QuertyException(errors)
        return parsed
    }

    /** `shop/orders.sql` generates `shop/OrdersQueries.kt`: the package's directory and the file's name. */
    private fun outputPath(sqlPath: String) = sqlPath.substringBeforeLast('/') + "/" + Naming.fileName(sqlPath)

    /** All snippets by name; a name defined twice is an error at the later definition. */
    private fun snippets(parsed: List<ParsedFile>): Map<String, SnippetDef> {
        val errors = mutableListOf<QuertyError>()
        val snippets = linkedMapOf<String, SnippetDef>()
        parsed.flatMap { it.snippets }.forEach { snippet ->
            val first = snippets.putIfAbsent(snippet.name, snippet)
            if (first != null) {
                errors += QuertyError(
                    snippet.body.file,
                    snippet.line,
                    "Duplicate snippet name '${snippet.name}'; also defined in ${first.body.file}:${first.line}",
                )
            }
        }
        if (errors.isNotEmpty()) throw QuertyException(errors)
        return snippets
    }

    private fun model(file: ParsedFile, query: QueryDef, sql: RewrittenQuery, describer: QueryDescriber): QueryModel =
        when (val result = describer.describe(sql.positionalSql())) {
            is DescribeResult.Described -> QueryModelBuilder.build(query, sql, result.description, file.fileImports)
            is DescribeResult.Failed -> {
                val (path, line) = result.position?.let(sql::locateServerOffset) ?: (query.body.file to query.line)
                throw QuertyException(listOf(QuertyError(path, line, "Postgres: ${result.message}")))
            }
        }

    private fun <T> collect(errors: MutableList<QuertyError>, block: () -> T): T? =
        try {
            block()
        } catch (e: QuertyException) {
            errors += e.errors
            null
        }

    /** Generated `*.kt` files under [outDir] (those starting with the Querty header), keyed like [render]'s output. */
    private fun generatedFiles(outDir: Path): Map<String, Path> {
        if (!outDir.isDirectory()) return emptyMap()
        return outDir.walk()
            .filter { it.isRegularFile() && it.extension == "kt" && Files.newBufferedReader(it).use { r -> r.readLine() }?.startsWith(HEADER) == true }
            .associateBy { it.relativeTo(outDir).invariantSeparatorsPathString }
    }

    /**
     * Writes [outputs] into a temp dir, then replaces the generated files in [outDir] with them: changed and new
     * files are moved in, generated files without a source are deleted along with directories that leaves empty.
     * Other files in [outDir] are never touched.
     */
    private fun write(outputs: Map<String, String>, outDir: Path) {
        val existing = generatedFiles(outDir)
        val blocked = outputs.keys.filter { it !in existing && outDir.resolve(it).exists() }
        if (blocked.isNotEmpty()) {
            throw QuertyException(blocked.map { QuertyError(outDir.resolve(it).toString(), 1, "Exists and was not generated by Querty; move it away") })
        }

        val temp = Files.createTempDirectory("querty")
        try {
            outputs.forEach { (path, text) -> temp.resolve(path).also { it.parent.createDirectories() }.writeText(text) }
            outputs.keys.forEach { path ->
                val target = outDir.resolve(path)
                val source = temp.resolve(path)
                if (path !in existing || !target.readBytes().contentEquals(source.readBytes())) {
                    target.parent.createDirectories()
                    Files.move(source, target, StandardCopyOption.REPLACE_EXISTING)
                }
            }
        } finally {
            temp.deleteRecursively()
        }

        (existing.keys - outputs.keys).forEach { path ->
            val file = outDir.resolve(path)
            file.deleteIfExists()
            var dir = file.parent
            while (dir != outDir && dir.listDirectoryEntries().isEmpty()) {
                dir.deleteIfExists()
                dir = dir.parent
            }
        }
    }
}
