package io.querty.codegen

/** Emits the Kotlin source for the queries of one `.sql` file: one object per query. */
object KotlinEmitter {
    fun emit(packageName: String, models: List<QueryModel>): String {
        require(models.isNotEmpty()) { "Nothing to emit: no queries" }
        val sqlFile = models.first().def.body.file.substringAfterLast('/').substringAfterLast('\\')
        return buildString {
            append("// Generated by Querty from $sqlFile. Do not edit.\n")
            append("package $packageName\n\n")
            (models.flatMap { it.imports } + models.flatMap(::runtimeNames).map { "io.querty.$it" })
                .distinct().sorted().forEach { append("import $it\n") }
            models.forEach {
                append("\n")
                emitQuery(it)
            }
        }
    }

    private fun StringBuilder.emitQuery(model: QueryModel) {
        val def = model.def
        def.doc?.let { doc ->
            val lines = doc.replace("*/", "*&#47;").replace("/*", "&#47;*").lines()
            if (lines.size == 1) {
                append("/** ${lines.single()} */\n")
            } else {
                append("/**\n")
                lines.forEach { append(if (it.isBlank()) " *\n" else " * $it\n") }
                append(" */\n")
            }
        }
        if (model.columns.any { it.type.isArray }) append("@Suppress(\"UNCHECKED_CAST\")\n")
        append("object ${model.objectName} {\n")
        if (model.columns.isNotEmpty()) {
            append("    data class Row(\n")
            model.columns.forEach { append("        val ${it.kotlinName}: ${columnType(it)},\n") }
            append("    )\n\n")
        }
        val template = model.rewritten
        append("    private val TEMPLATE = SqlTemplate(listOf(${template.parts.joinToString(", ") { literal(it) }}), ")
        append(if (template.refs.isEmpty()) "emptyList()" else "listOf(${template.refs.joinToString(", ")})")
        append(")\n\n")

        val signature = model.params.joinToString(", ") { "${it.kotlinName}: ${paramType(it)}" }
        val params = if (model.params.isEmpty()) {
            "emptyList()"
        } else {
            "listOf(${model.params.joinToString(", ") { "Param(${literal(it.sqlName)}, ${paramValue(it)}, PgType(${literal(it.type.name)}))" }})"
        }
        if (def.shape == Shape.AFFECTED) {
            append("    operator fun invoke($signature): AffectedQuery =\n")
            append("        AffectedQuery(TEMPLATE, $params)\n")
        } else {
            val query = when (def.shape) {
                Shape.ONE -> "OneQuery"
                Shape.OPTIONAL -> "OptionalQuery"
                else -> "ManyQuery"
            }
            append("    operator fun invoke($signature): $query<Row> =\n")
            append("        $query(TEMPLATE, $params) { r ->\n")
            append("            Row(\n")
            model.columns.forEachIndexed { i, column -> append("                ${column.kotlinName} = ${read(column, i)},\n") }
            append("            )\n")
            append("        }\n")
        }
        append("}\n")
    }

    /**
     * The `io.querty` names [model]'s code uses, imported one by one: a star import would lose to a same-named class
     * in the target package.
     */
    private fun runtimeNames(model: QueryModel): List<String> = buildList {
        add("SqlTemplate")
        add(
            when (model.def.shape) {
                Shape.ONE -> "OneQuery"
                Shape.OPTIONAL -> "OptionalQuery"
                Shape.MANY -> "ManyQuery"
                Shape.AFFECTED -> "AffectedQuery"
            },
        )
        if (model.params.isNotEmpty()) add("Param")
        if (model.params.isNotEmpty() || model.columns.any { it.type.isArray }) add("PgType")
        if (model.columns.any { !it.nullable }) add("notNull")
    }

    private fun elementType(decl: TypeDecl?, base: BaseType) = decl?.kotlinType ?: base.kotlinType

    private fun columnType(c: ColumnModel): String {
        val element = elementType(c.decl, c.baseType)
        return (if (c.type.isArray) "List<$element?>" else element) + if (c.nullable) "?" else ""
    }

    private fun paramType(p: ParamModel): String {
        val element = elementType(p.decl, p.baseType)
        return (if (p.type.isArray) "List<$element>" else element) + if (p.nullable) "?" else ""
    }

    /** Wraps a base value [expr] in the declared app type. */
    private fun wrap(decl: TypeDecl, expr: String) = if (decl.isEnum) "${decl.kotlinType}.valueOf($expr)" else "${decl.kotlinType}($expr)"

    private fun read(c: ColumnModel, i: Int): String {
        val decl = c.decl
        if (c.type.isArray) {
            val raw = "(r.list($i, PgType(${literal(c.type.elementType.name)})) as List<${c.baseType.kotlinType}?>?)"
            val mapped = if (decl == null) raw else "$raw?.map { e -> e?.let { ${wrap(decl, "it")} } }"
            return if (c.nullable) mapped else "notNull($mapped, ${literal(c.label)})"
        }
        val raw = "r.${c.baseType.readCall}($i)"
        return when {
            decl == null -> if (c.nullable) raw else "notNull($raw, ${literal(c.label)})"
            c.nullable -> "$raw?.let { ${wrap(decl, "it")} }"
            else -> wrap(decl, "notNull($raw, ${literal(c.label)})")
        }
    }

    private fun paramValue(p: ParamModel): String {
        val decl = p.decl ?: return p.kotlinName
        val unwrap = if (decl.isEnum) "name" else "value"
        val safe = if (p.nullable) "?" else ""
        return if (p.type.isArray) "${p.kotlinName}$safe.map { it.$unwrap }" else "${p.kotlinName}$safe.$unwrap"
    }

    /** [text] as a Kotlin string literal. */
    private fun literal(text: String): String = buildString {
        append('"')
        for (c in text) {
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                else -> append(c)
            }
        }
        append('"')
    }
}
