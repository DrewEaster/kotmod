package io.querty.codegen

import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

private const val PACKAGE = "io.kotmod.querty.example"

private val findOrder = """
    -- :name find-order :optional
    -- :doc Load one order by id
    -- :type id OrderId
    -- :type reason Reason
    -- :import com.acme.OrderId
    SELECT o.id, o.reason, o.placed_at
    FROM orders o
    WHERE o.id = :id
""".trimIndent()

private fun emit(vararg models: QueryModel) = KotlinEmitter.emit(PACKAGE, models.toList())

class KotlinEmitterTest {
    private val findOrderModel = model(
        findOrder,
        listOf("text"),
        listOf(col("id", "text", "orders", notNull = true), col("reason", "text", "orders"), col("placed_at", "timestamptz", "orders", notNull = true)),
    )

    @Test fun `emits the header, package and imports`() {
        val out = emit(findOrderModel)
        assertTrue(out.startsWith("// Generated by Querty from orders.sql. Do not edit.\npackage $PACKAGE\n\nimport com.acme.OrderId\nimport io.querty.OptionalQuery\nimport io.querty.Param\nimport io.querty.PgType\nimport io.querty.SqlTemplate\nimport io.querty.notNull\n\n"), out)
    }

    @Test fun `emits a value-class param and columns, nullable and not`() {
        val out = emit(findOrderModel)
        assertContains(out, "object FindOrder {")
        assertContains(out, "val id: OrderId,")
        assertContains(out, "val reason: Reason?,")
        assertContains(out, "val placedAt: kotlin.time.Instant,")
        assertContains(out, "operator fun invoke(id: OrderId): OptionalQuery<Row> =")
        assertContains(out, "OptionalQuery(TEMPLATE, listOf(Param(\"id\", id.value, PgType(\"text\")))) { r ->")
        assertContains(out, "id = OrderId(notNull(r.string(0), \"id\")),")
        assertContains(out, "reason = r.string(1)?.let { Reason(it) },")
        assertContains(out, "placedAt = notNull(r.instant(2), \"placed_at\"),")
    }

    @Test fun `emits the template with the user's line breaks`() {
        assertContains(
            emit(findOrderModel),
            "private val TEMPLATE = SqlTemplate(listOf(\"SELECT o.id, o.reason, o.placed_at\\nFROM orders o\\nWHERE o.id = \", \"\"), listOf(0))",
        )
    }

    @Test fun `a nullable value-class param uses safe calls`() {
        val m = model("-- :name q :affected\n-- :type id OrderId\n-- :nullable id\nDELETE FROM t WHERE id = :id", listOf("text"))
        val out = emit(m)
        assertContains(out, "operator fun invoke(id: OrderId?): AffectedQuery =")
        assertContains(out, "Param(\"id\", id?.value, PgType(\"text\"))")
    }

    @Test fun `emits an enum param and column`() {
        val m = model(
            "-- :name q :many\n-- :type status OrderStatus enum\n-- :nullable status\nSELECT status FROM orders WHERE status = :status",
            listOf("text"),
            listOf(col("status", "text", "orders", notNull = true)),
        )
        val out = emit(m)
        assertContains(out, "operator fun invoke(status: OrderStatus?): ManyQuery<Row> =")
        assertContains(out, "Param(\"status\", status?.name, PgType(\"text\"))")
        assertContains(out, "status = OrderStatus.valueOf(notNull(r.string(0), \"status\")),")

        val nullable = emit(model("-- :name q :many\n-- :type status OrderStatus enum\nSELECT status FROM orders", columns = listOf(col("status", "text"))))
        assertContains(nullable, "status = r.string(0)?.let { OrderStatus.valueOf(it) },")
    }

    @Test fun `emits a list param with ANY`() {
        val m = model(
            "-- :name q :many\n-- :type ids OrderId\nSELECT id FROM orders WHERE id = ANY(:ids) AND n = ANY(:ns)",
            listOf("_text", "_int4"),
            listOf(col("id", "text", "orders", notNull = true)),
        )
        val out = emit(m)
        assertContains(out, "operator fun invoke(ids: List<OrderId>, ns: List<Int>): ManyQuery<Row> =")
        assertContains(out, "Param(\"ids\", ids.map { it.value }, PgType(\"_text\"))")
        assertContains(out, "Param(\"ns\", ns, PgType(\"_int4\"))")
    }

    @Test fun `emits a list column with an unchecked cast`() {
        val m = model(
            "-- :name q :one\n-- :type ids OrderId\nSELECT array_agg(n) AS ns, array_agg(id) AS ids FROM t",
            columns = listOf(col("ns", "_int4"), col("ids", "_text")),
        )
        val out = emit(m)
        assertContains(out, "@Suppress(\"UNCHECKED_CAST\")\nobject Q {")
        assertContains(out, "val ns: List<Int?>?,")
        assertContains(out, "val ids: List<OrderId?>?,")
        assertContains(out, "ns = (r.list(0, PgType(\"int4\")) as List<Int?>?),")
        assertContains(out, "ids = (r.list(1, PgType(\"text\")) as List<String?>?)?.map { e -> e?.let { OrderId(it) } },")
        assertFalse(emit(findOrderModel).contains("@Suppress"))
    }

    @Test fun `each shape gives its query type`() {
        val columns = listOf(col("x", "int4"))
        assertContains(emit(model("-- :name q :one\nSELECT 1 AS x", columns = columns)), "operator fun invoke(): OneQuery<Row> =\n        OneQuery(TEMPLATE, emptyList()) { r ->")
        assertContains(emit(model("-- :name q :optional\nSELECT 1 AS x", columns = columns)), "OptionalQuery(TEMPLATE, emptyList()) { r ->")
        assertContains(emit(model("-- :name q :many\nSELECT 1 AS x", columns = columns)), "ManyQuery(TEMPLATE, emptyList()) { r ->")
        val affected = emit(model("-- :name q :affected\nDELETE FROM t"))
        assertContains(affected, "operator fun invoke(): AffectedQuery =\n        AffectedQuery(TEMPLATE, emptyList())\n")
        assertFalse(affected.contains("Row"))
        assertContains(affected, "SqlTemplate(listOf(\"DELETE FROM t\"), emptyList())")
    }

    @Test fun `escapes dollars, quotes and backslashes in SQL`() {
        val out = emit(model("-- :name q :affected\nUPDATE t SET a = \$\$x\"\\y\$\$, b = '\t'"))
        assertContains(out, "listOf(\"UPDATE t SET a = \\\$\\\$x\\\"\\\\y\\\$\\\$, b = '\\t'\")")
    }

    @Test fun `doc becomes KDoc`() {
        assertContains(emit(findOrderModel), "/** Load one order by id */\nobject FindOrder {")
        val multi = emit(model("-- :name q :affected\n-- :doc first\n-- :doc second\nDELETE FROM t"))
        assertContains(multi, "/**\n * first\n * second\n */\nobject Q {")
    }

    @Test fun `comment markers in a doc cannot open or close a comment`() {
        val out = emit(model("-- :name q :affected\n-- :doc see /* and */ here\nDELETE FROM t"))
        assertContains(out, "/** see &#47;* and *&#47; here */\nobject Q {")
    }

    @Test fun `imports only the runtime names a file uses`() {
        val out = emit(model("-- :name q :many\nSELECT array_agg(n) AS ns FROM t", columns = listOf(col("ns", "_int4"))))
        assertContains(out, "\nimport io.querty.ManyQuery\nimport io.querty.PgType\nimport io.querty.SqlTemplate\n\n")
        assertFalse(out.contains("import io.querty.*"))
        assertFalse(out.contains("import io.querty.Param\n"))
        assertFalse(out.contains("import io.querty.notNull"))
    }

    @Test fun `imports are deduplicated and sorted across queries`() {
        val a = model("-- :name a :affected\n-- :import com.b.B\n-- :import com.a.A\nDELETE FROM t", fileImports = listOf("com.c.C"))
        val b = model("-- :name b :affected\n-- :import com.a.A\nDELETE FROM t", fileImports = listOf("com.c.C"))
        val out = emit(a, b)
        assertContains(out, "import com.a.A\nimport com.b.B\nimport com.c.C\nimport io.querty.AffectedQuery\nimport io.querty.SqlTemplate\n\n")
        assertEquals(1, Regex("import com.a.A").findAll(out).count())
        assertContains(out, "object A {")
        assertContains(out, "object B {")
    }
}
