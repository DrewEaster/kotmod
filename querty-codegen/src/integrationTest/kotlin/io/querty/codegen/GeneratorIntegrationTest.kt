package io.querty.codegen

import org.jetbrains.kotlin.cli.common.ExitCode
import org.jetbrains.kotlin.cli.jvm.K2JVMCompiler
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.api.io.TempDir
import java.io.ByteArrayOutputStream
import java.io.PrintStream
import java.nio.file.Path
import java.nio.file.Paths
import kotlin.io.path.ExperimentalPathApi
import kotlin.io.path.copyToRecursively
import kotlin.io.path.createDirectories
import kotlin.io.path.deleteExisting
import kotlin.io.path.exists
import kotlin.io.path.invariantSeparatorsPathString
import kotlin.io.path.isRegularFile
import kotlin.io.path.readText
import kotlin.io.path.relativeTo
import kotlin.io.path.walk
import kotlin.io.path.writeText
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

@OptIn(ExperimentalPathApi::class)
class GeneratorIntegrationTest {
    @TempDir
    lateinit var dir: Path

    private val fixture: Path = Paths.get(javaClass.getResource("/fixture")!!.toURI())

    private val sql get() = dir.resolve("sql")
    private val out get() = dir.resolve("out")
    private val config get() = GeneratorConfig(sql, listOf(dir.resolve("schema")), out)

    private fun copyFixture() {
        fixture.copyToRecursively(dir, followLinks = false, overwrite = true)
    }

    private fun files(root: Path): List<String> =
        if (root.exists()) root.walk().filter { it.isRegularFile() }.map { it.relativeTo(root).invariantSeparatorsPathString }.sorted().toList() else emptyList()

    private fun edit(path: Path, from: String, to: String) {
        val text = path.readText()
        check(from in text) { "'$from' not in $path" }
        path.writeText(text.replace(from, to))
    }

    @Test
    fun `generates one file per sql file with the expected objects`() {
        copyFixture()

        Generator.generate(config)

        assertEquals(listOf("shop/OrdersQueries.kt"), files(out))
        val generated = out.resolve("shop/OrdersQueries.kt").readText()
        assertTrue(generated.startsWith("// Generated by Querty from orders.sql. Do not edit.\npackage shop\n"), generated)
        assertContains(generated, "object FindOrder {")
        assertContains(generated, "object CountOrders {")
        assertContains(generated, "object CustomerOrders {")
        assertContains(generated, "object SaveOrder {")
        assertContains(generated, "val customerName: String?,")
        assertContains(generated, "val status: OrderStatus,")
    }

    @Test
    fun `generated code compiles against the runtime`() {
        copyFixture()
        Generator.generate(config)

        val sources = files(out).map { out.resolve(it).toString() } + dir.resolve("kotlin/shop/Types.kt").toString()
        val classpath = listOf(io.querty.SqlTemplate::class.java, Unit::class.java)
            .map { Paths.get(it.protectionDomain.codeSource.location.toURI()).toString() }
            .distinct()
            .joinToString(java.io.File.pathSeparator)
        val messages = ByteArrayOutputStream()
        val exit = K2JVMCompiler().exec(
            PrintStream(messages),
            "-no-stdlib",
            "-no-reflect",
            "-classpath",
            classpath,
            "-d",
            dir.resolve("classes").toString(),
            *sources.toTypedArray(),
        )

        assertEquals(ExitCode.OK, exit, messages.toString())
        assertFalse("error:" in messages.toString(), messages.toString())
        assertTrue(dir.resolve("classes/shop/FindOrder.class").exists())
    }

    @Test
    fun `unknown column reports the sql file and line, through a snippet`() {
        copyFixture()
        edit(sql.resolve("shop/shared.sql"), "o.reason,", "o.nope,")

        val ex = assertThrows<QuertyException> { Generator.generate(config) }

        val error = ex.errors.single()
        assertEquals("shop/shared.sql", error.file)
        assertEquals(5, error.line)
        assertContains(error.message, "Postgres:")
        assertContains(error.message, "nope")
        assertEquals(emptyList(), files(out))
    }

    @Test
    fun `all errors across files are reported in one run`() {
        copyFixture()
        edit(sql.resolve("shop/orders.sql"), "FROM orders WHERE customer_id", "FROM orderz WHERE customer_id")
        sql.resolve("billing").createDirectories()
        sql.resolve("billing/invoices.sql").writeText("-- :name list-invoices :many\nSELECT id\nFROM invoices\n")

        val ex = assertThrows<QuertyException> { Generator.generate(config) }

        assertEquals(listOf("billing/invoices.sql" to 3, "shop/orders.sql" to 4), ex.errors.map { it.file to it.line })
        assertTrue(ex.errors.all { it.message.startsWith("Postgres: ") }, ex.errors.toString())
        assertEquals(emptyList(), files(out))
    }

    @Test
    fun `duplicate snippet names across files are an error at the second definition`() {
        copyFixture()
        sql.resolve("shop/zz.sql").writeText("-- :name q :many\nSELECT 1 AS n\n\n-- :snippet order-columns\nx\n")

        val ex = assertThrows<QuertyException> { Generator.generate(config) }

        assertEquals(listOf(QuertyError("shop/zz.sql", 4, "Duplicate snippet name 'order-columns'; also defined in shop/shared.sql:1")), ex.errors)
    }

    @Test
    fun `the same object name in two files of one package is an error at the second query`() {
        copyFixture()
        sql.resolve("shop/zz.sql").writeText("-- :name q :many\nSELECT 1 AS n\n\n-- :name find-order :many\nSELECT 1 AS n\n")

        val ex = assertThrows<QuertyException> { Generator.generate(config) }

        assertEquals(
            listOf(QuertyError("shop/zz.sql", 4, "Query 'find-order' generates object FindOrder in package shop, as does shop/orders.sql:6; rename one of them")),
            ex.errors,
        )
    }

    @Test
    fun `deleting a sql file removes its generated file on the next run`() {
        copyFixture()
        Generator.generate(config)
        out.resolve("other").createDirectories()
        out.resolve("other/Keep.kt").writeText("package other\n")
        out.resolve("shop/Notes.txt").writeText("// Generated by Querty, but not a .kt file\n")

        sql.resolve("shop/orders.sql").deleteExisting()
        Generator.generate(config)

        assertEquals(listOf("other/Keep.kt", "shop/Notes.txt"), files(out))

        out.resolve("shop/Notes.txt").deleteExisting()
        out.resolve("shop/StaleQueries.kt").writeText("// Generated by Querty from stale.sql. Do not edit.\n")
        Generator.generate(config)

        assertEquals(listOf("other/Keep.kt"), files(out))
        assertFalse(out.resolve("shop").exists())
    }

    @Test
    fun `check reports stale and is clean after generate`() {
        copyFixture()

        assertEquals(listOf("missing: shop/OrdersQueries.kt"), Generator.check(config))

        Generator.generate(config)
        assertEquals(emptyList(), Generator.check(config))

        out.resolve("shop/OrdersQueries.kt").writeText("// Generated by Querty from orders.sql. Do not edit.\n")
        out.resolve("shop/OldQueries.kt").writeText("// Generated by Querty from old.sql. Do not edit.\n")
        out.resolve("shop/Hand.kt").writeText("package shop\n")
        assertEquals(listOf("extra: shop/OldQueries.kt", "stale: shop/OrdersQueries.kt"), Generator.check(config))
    }

    @Test
    fun `main exits non-zero on errors`() {
        copyFixture()
        edit(sql.resolve("shop/shared.sql"), "o.reason,", "o.nope,")
        val args = arrayOf("--sql-dir", sql.toString(), "--schema", dir.resolve("schema").toString(), "--out", out.toString())

        val (generateExit, generateErr) = runMain(*args, "generate")
        assertEquals(1, generateExit)
        assertTrue(generateErr.startsWith("shop/shared.sql:5: Postgres: "), generateErr)

        edit(sql.resolve("shop/shared.sql"), "o.nope,", "o.reason,")
        val (checkExit, checkErr) = runMain(*args, "check")
        assertEquals(1, checkExit)
        assertEquals("missing: shop/OrdersQueries.kt\n", checkErr)

        val (usageExit, usageErr) = runMain("--sql-dir", sql.toString(), "generate")
        assertEquals(2, usageExit)
        assertContains(usageErr, "Usage:")

        assertEquals(0, runMain(*args, "generate").first)
        assertEquals(0, runMain(*args, "check").first)
    }

    private fun runMain(vararg args: String): Pair<Int, String> {
        val err = ByteArrayOutputStream()
        val saved = System.err
        System.setErr(PrintStream(err, true))
        try {
            return run(arrayOf(*args)) to err.toString()
        } finally {
            System.setErr(saved)
        }
    }
}
